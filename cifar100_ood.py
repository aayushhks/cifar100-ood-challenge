# ── Two-phase fit ────────────────────────────────────────────────────────────
def fit_part3_phase(model, train_loader, val_loader, optimizer, criterion,
                    epochs, scheduler=None,
                    mixup_alpha=0.0, cutmix_alpha=0.0, mixup_prob=0.0,
                    ckpt_path=None, phase_name=""):
    """One training phase.  Returns (history_dict, best_val_acc)."""
    history = {"train_acc": [], "val_acc": [], "train_loss": [], "val_loss": []}
    best_val = -1.0
    use_amp = (device.type == "cuda")
    scaler = torch.cuda.amp.GradScaler(enabled=use_amp)

    for ep in range(1, epochs + 1):
        model.train()
        tr_c = tr_t = 0; tr_l = 0.0
        for x, y in tqdm(train_loader,
                         desc=f"[{phase_name}] train {ep}/{epochs}", leave=False):
            x = x.to(device, non_blocking=True)
            y = y.to(device, non_blocking=True)
            r = np.random.random()
            if r < mixup_prob / 2 and mixup_alpha > 0:
                mx, ya, yb, lam = mixup_data(x, y, mixup_alpha)
            elif r < mixup_prob and cutmix_alpha > 0:
                mx, ya, yb, lam = cutmix_data(x, y, cutmix_alpha)
            else:
                mx, ya, yb, lam = x, y, y, 1.0
            optimizer.zero_grad(set_to_none=True)
            with torch.cuda.amp.autocast(enabled=use_amp):
                logits = model(mx)
                loss = lam * criterion(logits, ya) + (1 - lam) * criterion(logits, yb)
            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            scaler.step(optimizer); scaler.update()
            with torch.no_grad():
                tr_c += (logits.argmax(1) == y).sum().item(); tr_t += y.numel()
                tr_l += loss.item() * y.numel()
        if scheduler is not None:
            scheduler.step()

        model.eval()
        va_c = va_t = 0; va_l = 0.0
        with torch.no_grad():
            for x, y in val_loader:
                x, y = x.to(device), y.to(device)
                with torch.cuda.amp.autocast(enabled=use_amp):
                    logits = model(x)
                    loss = criterion(logits, y)
                va_c += (logits.argmax(1) == y).sum().item(); va_t += y.numel()
                va_l += loss.item() * y.numel()

        tr_a = tr_c / max(tr_t, 1); va_a = va_c / max(va_t, 1)
        history["train_acc"].append(tr_a); history["val_acc"].append(va_a)
        history["train_loss"].append(tr_l / max(tr_t, 1))
        history["val_loss"].append(va_l / max(va_t, 1))
        lr_now = optimizer.param_groups[0]["lr"]
        print(f"  [{phase_name}] Epoch {ep:03d}/{epochs} | lr {lr_now:.2e} | "
              f"train {tr_a:.4f} ({tr_l/max(tr_t,1):.3f}) | val {va_a:.4f}")

        if va_a > best_val:
            best_val = va_a
            if ckpt_path:
                torch.save({k: v.detach().cpu().clone()
                            for k, v in model.state_dict().items()},
                           ckpt_path + ".best.pt")
    return history, best_val


