# Part 3: EVA-02-Large @ 448 — model definition + helper utilities

# ImageNet normalization used by EVA-02 (different from CIFAR-100 stats)
_EVA_MEAN = torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1)
_EVA_STD  = torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1)


class EVA02LargeWrapper(nn.Module):
    """EVA-02-Large @ 448 wrapper that accepts CIFAR-normalised 32x32 inputs.

    During training the data pipeline already outputs ImageNet-normalised
    448x448 tensors (see make_part3_loaders), so forward() is a thin pass-
    through.  During OOD inference (predict_file), images arrive as CIFAR-
    normalised 32x32, so the wrapper de-normalises, upsamples, and
    re-normalises before passing to the backbone.
    """
    def __init__(self, num_classes: int = 100, target_size: int = 448):
        super().__init__()
        self.backbone = timm.create_model(
            "eva02_large_patch14_448.mim_m38m_ft_in22k_in1k",
            pretrained=True, num_classes=num_classes,
        )
        self.target_size = target_size
        # Buffers for on-the-fly re-normalisation (used in inference adapter path)
        self.register_buffer("cifar_mean", _CIFAR_MEAN)
        self.register_buffer("cifar_std",  _CIFAR_STD)
        self.register_buffer("model_mean", _EVA_MEAN)
        self.register_buffer("model_std",  _EVA_STD)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        """Accepts EITHER:
          - ImageNet-normalised 448x448 (from training loader) — passed straight through
          - CIFAR-normalised any-resolution (from OOD predict_file) — converted inline
        The heuristic: if spatial dim != target_size, assume CIFAR 32x32 inference path.
        """
        if x.shape[-1] != self.target_size:
            # De-normalise CIFAR → [0,1], upsample, re-normalise for EVA-02
            x = x * self.cifar_std + self.cifar_mean
            x = torch.clamp(x, 0.0, 1.0)
            x = F.interpolate(x, size=self.target_size, mode="bicubic",
                              align_corners=False, antialias=True)
            x = (x - self.model_mean) / self.model_std
        return self.backbone(x)


class WarmupCosineLR(torch.optim.lr_scheduler._LRScheduler):
    """Linear warmup then cosine decay."""
    def __init__(self, optimizer, warmup_epochs, total_epochs, last_epoch=-1):
        self.warmup_epochs = warmup_epochs
        self.total_epochs = total_epochs
        super().__init__(optimizer, last_epoch)

    def get_lr(self):
        e = self.last_epoch
        if e < self.warmup_epochs:
            s = (e + 1) / max(1, self.warmup_epochs)
        else:
            p = (e - self.warmup_epochs) / max(1, self.total_epochs - self.warmup_epochs)
            s = 0.5 * (1 + math.cos(math.pi * min(max(p, 0.0), 1.0)))
        return [base_lr * s for base_lr in self.base_lrs]


def cutmix_data(x, y, alpha=1.0):
    lam = float(np.random.beta(alpha, alpha)) if alpha > 0 else 1.0
    B, C, H, W = x.shape
    idx = torch.randperm(B, device=x.device)
    r = np.sqrt(1.0 - lam)
    cy, cx = np.random.randint(H), np.random.randint(W)
    y1 = max(0, cy - int(H * r) // 2); y2 = min(H, cy + int(H * r) // 2)
    x1 = max(0, cx - int(W * r) // 2); x2 = min(W, cx + int(W * r) // 2)
    mixed = x.clone(); mixed[:, :, y1:y2, x1:x2] = x[idx, :, y1:y2, x1:x2]
    lam = 1.0 - ((y2 - y1) * (x2 - x1) / (H * W))
    return mixed, y, y[idx], lam


