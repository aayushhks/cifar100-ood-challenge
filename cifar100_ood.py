# Part 1 training
def mixup_data(x, y, alpha=0.2):
    lam = float(np.random.beta(alpha, alpha)) if alpha > 0 else 1.0
    idx = torch.randperm(x.size(0), device=x.device)
    return lam * x + (1 - lam) * x[idx], y, y[idx], lam


def fit_part1(model, train_loader, val_loader, optimizer, criterion, scheduler,
              epochs, mixup_alpha, ckpt_path):
    history = {"train_acc": [], "val_acc": [], "train_loss": [], "val_loss": []}
    best_val = -1.0
    use_amp = (device.type == "cuda")
    scaler = torch.cuda.amp.GradScaler(enabled=use_amp)

    for ep in range(1, epochs + 1):
        model.train()
        tr_c, tr_t, tr_l = 0, 0, 0.0
        for x, y in tqdm(train_loader, desc=f"P1 train {ep}/{epochs}", leave=False):
            x = x.to(device, non_blocking=True); y = y.to(device, non_blocking=True)
            mx, ya, yb, lam = mixup_data(x, y, mixup_alpha)
            optimizer.zero_grad(set_to_none=True)
            with torch.cuda.amp.autocast(enabled=use_amp):
                logits = model(mx)
                loss = lam * criterion(logits, ya) + (1 - lam) * criterion(logits, yb)
            scaler.scale(loss).backward(); scaler.step(optimizer); scaler.update()
            with torch.no_grad():
                tr_c += (logits.argmax(1) == y).sum().item(); tr_t += y.numel()
                tr_l += loss.item() * y.numel()
        if scheduler is not None: scheduler.step()

        model.eval()
        va_c, va_t, va_l = 0, 0, 0.0
        with torch.no_grad():
            for x, y in val_loader:
                x, y = x.to(device), y.to(device)
                logits = model(x)
                va_l += F.cross_entropy(logits, y).item() * y.numel()
                va_c += (logits.argmax(1) == y).sum().item(); va_t += y.numel()
        tr_a = tr_c / max(tr_t, 1); va_a = va_c / max(va_t, 1)
        history["train_acc"].append(tr_a); history["val_acc"].append(va_a)
        history["train_loss"].append(tr_l / max(tr_t, 1))
        history["val_loss"].append(va_l / max(va_t, 1))
        print(f"  Epoch {ep:03d}/{epochs} | train_acc {tr_a:.4f} | val_acc {va_a:.4f}")

        if va_a > best_val:
            best_val = va_a
            torch.save({k: v.detach().cpu() for k, v in model.state_dict().items()},
                       ckpt_path + ".best.pt")
    return history, best_val


