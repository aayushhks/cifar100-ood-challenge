# Part 1: WRN-28-10 architecture
class _WRNBasicBlock(nn.Module):
    def __init__(self, in_planes, out_planes, stride, dropRate=0.0):
        super().__init__()
        self.bn1 = nn.BatchNorm2d(in_planes); self.relu1 = nn.ReLU(inplace=True)
        self.conv1 = nn.Conv2d(in_planes, out_planes, 3, stride=stride, padding=1, bias=False)
        self.bn2 = nn.BatchNorm2d(out_planes); self.relu2 = nn.ReLU(inplace=True)
        self.conv2 = nn.Conv2d(out_planes, out_planes, 3, stride=1, padding=1, bias=False)
        self.droprate = dropRate
        self.equalInOut = (in_planes == out_planes)
        self.convShortcut = None if self.equalInOut else nn.Conv2d(in_planes, out_planes, 1, stride=stride, padding=0, bias=False)

    def forward(self, x):
        if not self.equalInOut:
            x = self.relu1(self.bn1(x)); out = x
        else:
            out = self.relu1(self.bn1(x))
        out = self.relu2(self.bn2(self.conv1(out)))
        if self.droprate > 0:
            out = F.dropout(out, p=self.droprate, training=self.training)
        out = self.conv2(out)
        return (x if self.equalInOut else self.convShortcut(x)) + out


class WideResNet(nn.Module):
    def __init__(self, depth: int = 28, widen_factor: int = 10, dropRate: float = 0.3, num_classes: int = 100):
        super().__init__()
        nC = [16, 16 * widen_factor, 32 * widen_factor, 64 * widen_factor]
        n = (depth - 4) // 6
        self.conv1 = nn.Conv2d(3, nC[0], 3, stride=1, padding=1, bias=False)
        self.block1 = self._make_layer(n, nC[0], nC[1], 1, dropRate)
        self.block2 = self._make_layer(n, nC[1], nC[2], 2, dropRate)
        self.block3 = self._make_layer(n, nC[2], nC[3], 2, dropRate)
        self.bn1 = nn.BatchNorm2d(nC[3]); self.relu = nn.ReLU(inplace=True)
        self.fc = nn.Linear(nC[3], num_classes)
        self.nChannels = nC[3]
        for m in self.modules():
            if isinstance(m, nn.Conv2d):
                nn.init.kaiming_normal_(m.weight, mode="fan_out", nonlinearity="relu")
            elif isinstance(m, nn.BatchNorm2d):
                nn.init.constant_(m.weight, 1); nn.init.constant_(m.bias, 0)
            elif isinstance(m, nn.Linear):
                nn.init.constant_(m.bias, 0)

    def _make_layer(self, nb, in_planes, out_planes, stride, dropRate):
        layers = []
        for i in range(int(nb)):
            layers.append(_WRNBasicBlock(in_planes if i == 0 else out_planes, out_planes,
                                         stride if i == 0 else 1, dropRate))
        return nn.Sequential(*layers)

    def forward(self, x):
        out = self.conv1(x)
        out = self.block1(out); out = self.block2(out); out = self.block3(out)
        out = self.relu(self.bn1(out))
        out = F.avg_pool2d(out, 8).view(-1, self.nChannels)
        return self.fc(out)


